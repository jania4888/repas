import { JournalEntryDto } from '../../services/accounting.service';
import { buildJournalHistory, journalHistoryRange } from './entry-journal-history.logic';

describe('buildJournalHistory', () => {
  const today = new Date(2026, 9, 16);

  function entry(
    id: string,
    number: number,
    lines: JournalEntryDto['lines'],
    pieceRef: string | null = null
  ): JournalEntryDto {
    return {
      id,
      entryNumber: number,
      journalCode: 'JA',
      entryDate: '2026-10-01',
      label: `Pièce ${number}`,
      isAutoGenerated: false,
      isReversed: false,
      status: 1,
      isDraft: false,
      pieceRef,
      pieceDate: '2026-09-30',
      attachmentCount: 0,
      lines
    };
  }

  function line(
    lineNumber: number,
    accountNumber: string,
    debit: number,
    credit: number
  ): JournalEntryDto['lines'][number] {
    return {
      id: `l-${lineNumber}`,
      lineNumber,
      accountNumber,
      label: `Ligne ${lineNumber}`,
      debit,
      credit,
      currency: 'TND'
    };
  }

  it('garde l’ordre du serveur, vingt pièces, et les lignes sous leur pièce', () => {
    const entries = Array.from({ length: 21 }, (_, index) =>
      entry(`id-${index}`, 21 - index, [line(2, '401', 0, 10), line(1, '607', 10, 0)])
    );

    const docs = buildJournalHistory(entries, {
      accountLabel: number => (number === '607' ? 'Achats' : null)
    });

    expect(docs.length).toBe(20);
    expect(docs.map(doc => doc.id)).toEqual(entries.slice(0, 20).map(item => item.id));
    expect(docs[0].lines.map(item => item.lineNumber)).toEqual([1, 2]);
    expect(docs[0].lines[0].accountLabel).toBe('Achats');
    expect(docs[0].lines[1].accountLabel).toBeNull();
    expect(docs[0].documentNumber).toBe('JA 21');
  });

  it('affiche le total débit si la pièce est équilibrée, sinon l’écart', () => {
    const [balanced, unbalanced] = buildJournalHistory([
      entry('ok', 1, [line(1, '607', 10, 0), line(2, '401', 0, 10)], 'FAC-1'),
      entry('gap', 2, [line(1, '607', 10, 0), line(2, '401', 0, 7)], '   ')
    ]);

    expect(balanced.amount).toBe(10);
    expect(balanced.imbalance).toBeNull();
    expect(balanced.pieceRef).toBe('FAC-1');

    expect(unbalanced.imbalance).toBe(3);
    expect(unbalanced.pieceRef).toBeNull();
  });

  it('ouvre une fenêtre de 365 jours jusqu’à la date locale', () => {
    const range = journalHistoryRange(today);
    expect(range.to).toEqual(new Date(2026, 9, 16));
    expect(range.from).toEqual(new Date(2025, 9, 16));
  });
});
