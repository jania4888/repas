import { ComponentFixture, TestBed } from '@angular/core/testing';
import { Router } from '@angular/router';
import { Subject } from 'rxjs';
import { AccountingService, JournalEntryDto } from '../../services/accounting.service';
import { AuthService } from '@core/services/auth.service';
import { EntryFormStore } from '../services/entry-form.store';
import { EntryReferenceStore } from '../services/entry-reference.store';
import { EntryJournalHistoryComponent, EntryJournalHistoryRefresh } from './entry-journal-history.component';

describe('EntryJournalHistoryComponent', () => {
  interface Call {
    code: string | undefined;
    from: Date;
    to: Date;
    take: number | undefined;
    subject: Subject<{ success: boolean; data?: JournalEntryDto[]; error?: string }>;
  }

  let calls: Call[];
  let store: EntryFormStore;
  let navigate: jasmine.Spy;
  let firm: boolean;
  let delegated: boolean;

  beforeEach(async () => {
    calls = [];
    firm = true;
    delegated = true;
    navigate = jasmine.createSpy('navigate').and.resolveTo(true);
    await TestBed.configureTestingModule({
      imports: [EntryJournalHistoryComponent],
      providers: [
        EntryFormStore,
        EntryJournalHistoryRefresh,
        {
          provide: EntryReferenceStore,
          useValue: {
            findAccountByNumber: (number: string) => number === '607' ? { label: 'Achats' } : undefined
          }
        },
        {
          provide: AccountingService,
          useValue: {
            getJournal: (code: string | undefined, from: Date, to: Date, take?: number) => {
              const subject = new Subject<{ success: boolean; data?: JournalEntryDto[]; error?: string }>();
              calls.push({ code, from, to, take, subject });
              return subject.asObservable();
            }
          }
        },
        {
          provide: AuthService,
          useValue: {
            hasPermission: () => true,
            isAccountingFirm: () => firm,
            isDelegatedMode: () => delegated
          }
        },
        { provide: Router, useValue: { navigate } }
      ]
    }).compileComponents();

    store = TestBed.inject(EntryFormStore);
    store.journalCode.set('JA');
  });

  function entry(id: string, journal: string, draft: boolean, pieceRef: string | null = null): JournalEntryDto {
    return {
      id,
      entryNumber: draft ? 4 : 9,
      journalCode: journal,
      entryDate: '2026-10-01',
      label: draft ? 'Brouillon fournisseur' : 'Facture validée',
      isAutoGenerated: false,
      isReversed: false,
      status: draft ? 0 : 1,
      isDraft: draft,
      pieceRef,
      pieceDate: pieceRef ? '2026-09-28' : null,
      attachmentCount: 0,
      lines: [
        { id: `${id}-2`, lineNumber: 2, accountNumber: '4011', label: 'Fournisseur', debit: 0, credit: 100, currency: 'TND' },
        { id: `${id}-1`, lineNumber: 1, accountNumber: '607', label: 'Achats', debit: 100, credit: 0, currency: 'TND' }
      ]
    };
  }

  async function settle(fixture: ComponentFixture<EntryJournalHistoryComponent>): Promise<void> {
    fixture.detectChanges();
    await fixture.whenStable();
    fixture.detectChanges();
  }

  it('demande le journal choisi, ignore la réponse périmée et ouvre seulement le brouillon', async () => {
    const before = sessionStorage.length;
    const fixture = TestBed.createComponent(EntryJournalHistoryComponent);
    await settle(fixture);

    expect(calls.length).toBe(1);
    expect(calls[0].code).toBe('JA');
    expect(calls[0].take).toBe(20);
    expect(calls[0].to.getFullYear()).toBe(calls[0].from.getFullYear() + 1);
    expect(calls[0].to.getMonth()).toBe(calls[0].from.getMonth());
    expect(calls[0].to.getDate()).toBe(calls[0].from.getDate());

    store.journalCode.set('JV');
    await settle(fixture);
    expect(calls.length).toBe(2);
    expect(calls[1].code).toBe('JV');

    calls[0].subject.next({ success: true, data: [entry('old', 'JA', true, 'FAC-OLD')] });
    await settle(fixture);
    expect(fixture.nativeElement.textContent).not.toContain('JA 4');

    calls[1].subject.next({
      success: true,
      data: [entry('draft-1', 'JV', true, 'FAC-1'), entry('valid-1', 'JV', false)]
    });
    await settle(fixture);

    const text = fixture.nativeElement.textContent as string;
    expect(text).toContain('JV 4');
    expect(text).toContain('JV 9');
    expect(text).toContain('Achats');
    expect(text).toContain('Pièce FAC-1');
    expect(text).not.toContain('FAC-OLD');
    const rows = fixture.nativeElement.querySelectorAll('.entry-journal-history__lines tbody tr');
    expect(rows[0].textContent).toContain('607');
    expect(rows[1].textContent).toContain('4011');

    const openButtons = fixture.nativeElement.querySelectorAll('.entry-journal-history__open');
    expect(openButtons.length).toBe(1);
    openButtons[0].click();
    expect(navigate).toHaveBeenCalledWith(['/accounting/manual-entry'], {
      queryParams: { entryId: 'draft-1' }
    });
    expect(sessionStorage.length).toBe(before);

    TestBed.inject(EntryJournalHistoryRefresh).poke();
    await settle(fixture);
    expect(calls.length).toBe(3);
    expect(calls[2].code).toBe('JV');
    expect(calls[2].take).toBe(20);
  });

  it('affiche l’erreur sans conserver les lignes d’un autre journal', async () => {
    const fixture = TestBed.createComponent(EntryJournalHistoryComponent);
    await settle(fixture);

    calls[0].subject.next({ success: true, data: [entry('draft-1', 'JA', true, 'FAC-1')] });
    await settle(fixture);
    expect(fixture.nativeElement.textContent).toContain('JA 4');

    store.journalCode.set('JB');
    await settle(fixture);
    calls.at(-1)?.subject.error(new Error('réseau'));
    await settle(fixture);

    expect(fixture.nativeElement.textContent).toContain('Impossible de charger les dernières écritures.');
    expect(fixture.nativeElement.textContent).not.toContain('JA 4');
    expect(fixture.nativeElement.querySelector('.entry-journal-history__lines')).toBeNull();
  });

  it('masque Ouvrir quand la modification de brouillon n’est pas autorisée', async () => {
    firm = false;
    delegated = false;
    const fixture = TestBed.createComponent(EntryJournalHistoryComponent);
    await settle(fixture);
    calls[0].subject.next({ success: true, data: [entry('draft-1', 'JA', true)] });
    await settle(fixture);

    expect(fixture.nativeElement.querySelector('.entry-journal-history__open')).toBeNull();
    expect(navigate).not.toHaveBeenCalled();
  });
});
