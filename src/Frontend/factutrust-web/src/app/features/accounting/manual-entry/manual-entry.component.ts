export class ManualEntryComponent implements OnInit {
  private readonly errors = inject(ErrorHandlerService);
  readonly store = inject(EntryFormStore);
  readonly refs = inject(EntryReferenceStore);
  private readonly submitService = inject(EntrySubmitService);
  private readonly api = inject(AccountingService);
  private readonly router = inject(Router);
  private readonly route = inject(ActivatedRoute);
  private readonly toast = inject(ToastService);
  private readonly destroyRef = inject(DestroyRef);
  private readonly draftStore = inject(ManualEntryDraftService);
  private readonly confirmationService = inject(ConfirmationService);

  readonly pendingDraft = signal<ManualEntryDraft | null>(null);
  readonly showTemplatePicker = signal(false);
  readonly showSaveTemplate = signal(false);
  readonly savingTemplate = signal(false);
  readonly pendingFiles = signal<File[]>([]);
  readonly tabIndex = signal(0);
  readonly documentImportVisible = signal(false);

  private draftInitialized = signal(false);
  private readonly returnFrom = signal<string | null>(null);
  private readonly returnTo = signal<string | null>(null);
  private readonly returnJournal = signal<string | null>(null);

  readonly pageTitle = computed(() => {
    if (!this.store.editingLocked()) {
      return 'Saisie des écritures comptables';
    }
    const n = this.store.editingEntryNumber();
    const journal = this.store.journalCode();
    return n != null
      ? $localize`:@@ui.tern.modification.de.l.ecriture.ph.n.ph.brouill.769405:Modification de l'écriture ${journal}:p0: n° ${n}:p1: — Brouillon`
      : $localize`:@@ui.tern.modification.de.l.ecriture.brouillon.2edf28:Modification de l'écriture — Brouillon`;
  });

  readonly pageSubtitle = computed(() =>
    this.store.editingLocked()
      ? $localize`:@@ui.tern.corrigez.les.lignes.puis.enregistrez.la.va.e22392:Corrigez les lignes puis enregistrez. La validation se fait ensuite depuis le journal.`
      : $localize`:@@ui.tern.ecriture.de.journal.multi.lignes.avec.equi.daae00:Écriture de journal multi-lignes avec équilibrage automatique`
  );

  readonly sourceLabel = computed(() => sourceEntityLabel(this.store.sourceEntityType()));

  private readonly tabIds: EntryTabId[] = ['standard', 'guided', 'template', 'recurring'];

  readonly buildManualEntryAnalyzePayload = (): unknown =>
    wrapLegacyAnalyzePayload(
      'accounting-manual-entry',
      {
        screen: 'accounting-manual-entry',
        entry: {
          journalCode: this.store.journalCode() || null,
          entryDate: this.store.entryDate() || null,
          label: this.store.entryLabel() || null,
          isBalanced: this.store.isBalanced(),
          totalDebit: this.store.totals().debit,
          totalCredit: this.store.totals().credit
        },
        lines: this.store.lines().map(l => ({
          accountNumber: l.accountNumber || null,
          label: l.lineLabel || null,
          debit: l.debit,
          credit: l.credit
        }))
      } as Record<string, unknown>,
      { rowsKey: 'lines' }
    );

  constructor() {
    let saveTimer: ReturnType<typeof setTimeout> | null = null;
    effect(() => {
      this.store.toDraftPayload();
      if (!this.draftInitialized()) return;
      if (this.store.editingLocked()) return;
      if (saveTimer) clearTimeout(saveTimer);
      saveTimer = setTimeout(() => {
        if (!this.store.hasUserInput()) {
          this.draftStore.clear();
          return;
        }
        this.draftStore.save(this.store.toDraftPayload());
      }, 800);
    });

    effect(() => {
      this.store.setAccounts(this.refs.accounts());
      this.store.setPeriods(this.refs.periods());
      const opts = this.refs.journalOptions();
      if (opts.length > 0) this.store.setJournalOptions(opts);
    });
  }

  ngOnInit(): void {
    this.refs.loadAll();

    const qp = this.route.snapshot.queryParamMap;
    this.returnFrom.set(qp.get('returnFrom'));
    this.returnTo.set(qp.get('returnTo'));
    this.returnJournal.set(qp.get('returnJournal'));
    const entryId = qp.get('entryId');
    if (entryId) {
      this.loadExistingEntry(entryId);
      return;
    }

    const draft = this.draftStore.load();
    if (draft && this.draftStore.isMeaningful(draft)) {
      this.pendingDraft.set(draft);
    } else {
      this.draftStore.clear();
      this.draftInitialized.set(true);
    }
  }

  onTabChange(index: string | number): void {
    const tabIndex = typeof index === 'number' ? index : Number(index);
    this.tabIndex.set(tabIndex);
    this.store.activeTab.set(this.tabIds[tabIndex] ?? 'standard');
  }

  submit(afterSuccess: 'navigate' | 'reset' | 'duplicate' = 'navigate'): void {
    if (this.store.editingLocked()) {
      afterSuccess = 'navigate';
    }
    const letteredCodes = this.store.letteredGroupCodes();
    if (letteredCodes.length > 0) {
      this.confirmationService.confirm({
        message:
          `Enregistrer délettrera le(s) groupe(s) ${letteredCodes.join(', ')} : toutes leurs lignes ` +
          'redeviendront lettrables, y compris celles d\'autres écritures. Continuer ?',
        header: 'Écriture lettrée',
        acceptLabel: $localize`:@@manual-entry.component.acceptLabel.D_lettrer_et_enr:Délettrer et enregistrer`,
        rejectLabel: $localize`:@@manual-entry.component.rejectLabel.Annuler:Annuler`,
        accept: () => this.confirmWorkNotesThenSubmit(afterSuccess)
      });
      return;
    }
    this.confirmWorkNotesThenSubmit(afterSuccess);
  }

  private confirmWorkNotesThenSubmit(afterSuccess: 'navigate' | 'reset' | 'duplicate'): void {
    if (this.store.workNotes().trim() && afterSuccess !== 'duplicate') {
      this.confirmationService.confirm({
        message: 'La note de travail ne sera pas enregistrée en comptabilité. Continuer ?',
        header: 'Confirmation',
        acceptLabel: $localize`:@@manual-entry.component.acceptLabel.Continuer:Continuer`,
        rejectLabel: $localize`:@@manual-entry.component.rejectLabel.Annuler:Annuler`,
        accept: () => this.executeSubmit(afterSuccess)
      });
      return;
    }

    this.executeSubmit(afterSuccess);
  }

  private executeSubmit(afterSuccess: 'navigate' | 'reset' | 'duplicate'): void {
    this.submitService
      .submit(this.store, this.pendingFiles(), afterSuccess)
      .pipe(takeUntilDestroyed(this.destroyRef))
      .subscribe(result => {
        if (result.success) {
          this.pendingFiles.set([]);
          this.store.letteredGroupCodes.set([]);
          this.submitService.handleSubmitSuccess(
            this.store,
            result,
            afterSuccess,
            (jc, dt) => this.navigateToJournal(jc, dt),
            () => this.draftStore.clear()
          );
        }
      });
  }

  openDocumentImport(): void {
    if (this.store.editingLocked()) return;
    this.documentImportVisible.set(true);
  }

  /**
   * Applique une proposition d'écriture importée : lignes + en-tête dans le formulaire, et le
   * fichier source part comme pièce jointe (même mécanique que les pièces ajoutées à la main).
   */
  onDocumentProposalApplied(event: { proposal: JournalEntryProposal; file: File }): void {
    this.store.applyDocumentProposal(event.proposal);
    this.pendingFiles.update(files => [...files, event.file]);
    this.tabIndex.set(0);
    this.store.activeTab.set('standard');
    const lineCount = event.proposal.lines.filter(
      l => l.debit > 0 || l.credit > 0
    ).length;
    this.toast.add({
      severity: 'success',
      summary: $localize`:@@manual-entry.component.summary.Proposition_appl:Proposition appliquée`,
      detail: `${lineCount} ligne(s) posée(s). Vérifiez avant d'enregistrer.`
    });
  }

  private navigateToJournal(journalCode: string, date: string): void {
    const from = this.returnFrom() || date;
    const to = this.returnTo() || date;
    const jc = this.returnJournal() || journalCode;
    this.router.navigate(['/accounting/journal'], {
      queryParams: { journalCode: jc || undefined, from, to }
    });
  }

  cancelEdit(): void {
    this.navigateToJournal(this.store.journalCode(), this.store.entryDate());
  }

  private loadExistingEntry(entryId: string): void {
    this.store.loading.set(true);
    this.api.getJournalEntry(entryId)
      .pipe(takeUntilDestroyed(this.destroyRef))
      .subscribe({
        next: res => {
          this.store.loading.set(false);
          if (!res.success || !res.data) {
            this.leaveEditWithError(res.error ?? $localize`:@@ui.tern.impossible.de.charger.l.ecriture.5fb160:Impossible de charger l'écriture.`);
            return;
          }
          const entry = res.data;
          if (!entry.isDraft) {
            this.leaveEditWithError("Seule une écriture en brouillon peut être modifiée.");
            return;
          }
          this.store.loadFromEntry(entry);
          this.draftInitialized.set(true);
        },
        error: err => {
          this.store.loading.set(false);
          this.leaveEditWithError(this.errors.extractErrorMessage(err, "Erreur réseau lors du chargement de l'écriture."));
        }
      });
  }

  private leaveEditWithError(message: string): void {
    this.toast.add({ severity: 'error', summary: $localize`:@@manual-entry.component.summary.Modification_imp:Modification impossible`, detail: message, life: 6000 });
    this.router.navigate(['/accounting/journal'], {
      queryParams: {
        journalCode: this.returnJournal() || undefined,
        from: this.returnFrom() || undefined,
        to: this.returnTo() || undefined
      }
    });
  }

  restoreDraft(): void {
    const draft = this.pendingDraft();
    if (!draft) return;
    this.store.restoreFromDraft(draft);
    if (draft.activeTab) {
      const idx = this.tabIds.indexOf(draft.activeTab);
      if (idx >= 0) this.tabIndex.set(idx);
    }
    this.pendingDraft.set(null);
    this.draftInitialized.set(true);
    this.toast.add({
      severity: 'info',
      summary: $localize`:@@manual-entry.component.summary.Brouillon_restau:Brouillon restauré`,
      detail: $localize`:@@manual-entry.component.detail.Votre_saisie_a_:Votre saisie a été restaurée. Vérifiez les montants avant d'enregistrer.`,
      life: 4000
    });
  }

  discardDraft(): void {
    this.draftStore.clear();
    this.pendingDraft.set(null);
    this.draftInitialized.set(true);
  }

  resetWithConfirm(): void {
    if (this.store.editingLocked()) {
      const id = this.store.editingEntryId();
      if (id) this.loadExistingEntry(id);
      return;
    }
    if (!this.store.hasUserInput()) {
      this.store.resetForm();
      return;
    }
    this.confirmationService.confirm({
      message: 'Voulez-vous vraiment vider le formulaire ? Toutes les saisies en cours seront perdues.',
      header: 'Confirmation',
      acceptLabel: $localize`:@@manual-entry.component.acceptLabel.Vider:Vider`,
      rejectLabel: $localize`:@@manual-entry.component.rejectLabel.Annuler:Annuler`,
      accept: () => {
        this.store.resetForm();
        this.pendingFiles.set([]);
      }
    });
  }

  openTemplatePicker(): void {
    if (this.store.editingLocked()) return;
    this.showTemplatePicker.set(true);
  }
  closeTemplatePicker(): void { this.showTemplatePicker.set(false); }

  onTemplateSelected(template: JournalEntryTemplateDto): void {
    if (this.store.hasUserInput()) {
      this.confirmationService.confirm({
        message: `Charger le modèle « ${template.name} » va remplacer la saisie en cours. Voulez-vous continuer ?`,
        header: 'Confirmation',
        acceptLabel: $localize`:@@manual-entry.component.acceptLabel.Continuer:Continuer`,
        rejectLabel: $localize`:@@manual-entry.component.rejectLabel.Annuler:Annuler`,
        accept: () => this.applySelectedTemplate(template)
      });
      return;
    }
    this.applySelectedTemplate(template);
  }

  private applySelectedTemplate(template: JournalEntryTemplateDto): void {
    this.applyTemplate(template);
    this.tabIndex.set(0);
    this.closeTemplatePicker();
  }

  private applyTemplate(template: JournalEntryTemplateDto): void {
    this.store.applyHeaderFromTemplate(template.journalCode, template.labelTemplate ?? null);
    this.store.applyLinesFromTemplate(
      template.lines
        .slice()
        .sort((a, b) => a.lineNumber - b.lineNumber)
        .map(l => ({
          accountNumber: l.accountNumber,
          lineLabel: l.lineLabelTemplate ?? '',
          debit: l.fixedDebit ?? null,
          credit: l.fixedCredit ?? null
        }))
    );
    this.toast.add({
      severity: 'info',
      summary: $localize`:@@manual-entry.component.summary.Modèle charg:Modèle chargé`,
      detail: `Le modèle « ${template.name} » a été chargé.`,
      life: 4000
    });
  }

  openSaveTemplate(): void {
    if (!this.store.canSaveAsTemplate()) {
      this.toast.add({
        severity: 'warn',
        summary: $localize`:@@manual-entry.component.summary.Sauvegarde i:Sauvegarde impossible`,
        detail: $localize`:@@manual-entry.component.detail.Veuillez_saisir_:Veuillez saisir au moins 2 lignes avec un numéro de compte.`,
        life: 5000
      });
      return;
    }
    this.showSaveTemplate.set(true);
  }

  closeSaveTemplate(): void { this.showSaveTemplate.set(false); }

  onSaveAsTemplate(payload: SaveTemplatePayload): void {
    const linesWithAccount = this.store.lines().filter(l => l.accountNumber.trim().length > 0);
    if (linesWithAccount.length < 2) return;

    const request: CreateJournalEntryTemplateRequest = {
      name: payload.name,
      description: payload.description || null,
      journalCode: payload.journalCode,
      labelTemplate: payload.labelTemplate || null,
      lines: linesWithAccount.map((l, idx) => ({
        lineNumber: idx + 1,
        accountNumber: l.accountNumber.trim(),
        lineLabelTemplate: l.lineLabel.trim() || null,
        fixedDebit: payload.keepAmounts ? (l.debit ?? null) : null,
        fixedCredit: payload.keepAmounts ? (l.credit ?? null) : null
      }))
    };

    this.savingTemplate.set(true);
    this.api.createJournalTemplate(request)
      .pipe(takeUntilDestroyed(this.destroyRef))
      .subscribe({
        next: res => {
          this.savingTemplate.set(false);
          if (res.success) {
            this.closeSaveTemplate();
            this.toast.add({ severity: 'success', summary: $localize`:@@manual-entry.component.summary.Modèle sauve:Modèle sauvegardé`, detail: `Le modèle « ${payload.name} » est disponible.`, life: 5000 });
          } else {
            this.toast.add({ severity: 'error', summary: $localize`:@@manual-entry.component.summary.Échec:Échec`, detail: res.error ?? $localize`:@@ui.tern.erreur.ab546c:Erreur`, life: 6000 });
          }
        },
        error: err => {
          this.savingTemplate.set(false);
          this.toast.add({ severity: 'error', summary: $localize`:@@manual-entry.component.summary.Impossible d:Impossible de sauvegarder.`, detail: this.errors.extractErrorMessage(err, 'Erreur réseau'), life: 6000 });
        }
      });
  }

  @HostListener('document:keydown', ['$event'])
  onKeydown(event: KeyboardEvent): void {
    if (event.key === 'Escape') {
      if (this.showTemplatePicker()) { this.closeTemplatePicker(); event.preventDefault(); return; }
      if (this.showSaveTemplate()) { this.closeSaveTemplate(); event.preventDefault(); return; }
      return;
    }
    // La modale d'import est un p-dialog : il gère Échap lui-même. En revanche les raccourcis
    // d'édition ne doivent pas traverser la modale — Ctrl+S enregistrerait l'écriture en cours
    // pendant l'analyse d'une facture.
    if (this.showTemplatePicker() || this.showSaveTemplate() || this.documentImportVisible()) return;

    if ((event.ctrlKey || event.metaKey) && (event.key === 's' || event.key === 'S')) {
      event.preventDefault();
      if (!this.store.canSubmit()) return;
      this.submit(event.shiftKey && !this.store.editingLocked() ? 'reset' : 'navigate');
      return;
    }

    if (event.altKey && !event.ctrlKey && !event.metaKey) {
      switch (event.key.toLowerCase()) {
        case 'l': event.preventDefault(); this.store.addLine(); break;
        case 'b': event.preventDefault(); if (this.store.canAutoBalance()) this.store.autoBalance(); break;
        case 'm': event.preventDefault(); if (!this.store.editingLocked()) this.openTemplatePicker(); break;
        case 'n': event.preventDefault(); this.resetWithConfirm(); break;
      }
    }
  }
}

