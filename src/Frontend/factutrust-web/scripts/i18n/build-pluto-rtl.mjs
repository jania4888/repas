#!/usr/bin/env node
/**
 * Génère src/styles/rtl/pluto-rtl.generated.css via postcss-rtlcss (surcharges RTL Pluto).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';
import postcssRTLCSS from 'postcss-rtlcss';
import { Mode, Source } from 'postcss-rtlcss/options';

const WEB = path.resolve(fileURLToPath(new URL('../..', import.meta.url)));
const SRC = path.join(WEB, 'src/assets/theme/pluto/style.css');
const OUT = path.join(WEB, 'src/styles/rtl/pluto-rtl.generated.css');

async function main() {
  if (!fs.existsSync(SRC)) {
    console.error('build-pluto-rtl: missing', SRC);
    process.exit(1);
  }

  const css = fs.readFileSync(SRC, 'utf8');
  const result = await postcss([
    postcssRTLCSS({
      mode: Mode.override,
      source: Source.ltr,
      rtlPrefix: "[dir='rtl']",
      ltrPrefix: "[dir='ltr']",
      processUrls: false,
      processKeyFrames: true
    })
  ]).process(css, { from: SRC });

  const header = `/* Generated by scripts/i18n/build-pluto-rtl.mjs — do not edit. */\n`;
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, header + result.css.trim() + '\n', 'utf8');
  console.log('build-pluto-rtl: wrote', path.relative(WEB, OUT), `(${result.css.length} bytes)`);
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
