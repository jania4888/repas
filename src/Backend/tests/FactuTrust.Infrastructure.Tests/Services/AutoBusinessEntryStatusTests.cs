namespace FactuTrust.Infrastructure.Tests.Services;

/// <summary>
/// Les pièces métier naissent Validée même quand le brouillard est actif. L'extourne de ces
/// pièces est elle aussi Validée. Un brouillon historique reste supprimé à l'annulation
/// (couvert par <c>CancelInvoice_WithDraftOriginal_DeletesDraftInsteadOfReversing</c>).
/// </summary>
public sealed class AutoBusinessEntryStatusTests
{
    [Fact]
    public async Task BrouillardEnabled_SaleEntryIsCreatedAsValideeWithoutValidator()
    {
        var invoice = NewSaleInvoice();
        AddLine(invoice, "Prestation", 100m);
        SetStamp(invoice, 1m);

        var (service, captured, _) = BuildService();
        var result = await service.GenerateInvoiceSaleEntryAsync(invoice, CancellationToken.None);

        Assert.True(result.IsSuccess, result.Error?.Description);
        var entry = Assert.Single(captured);
        Assert.Equal(JournalEntryStatus.Validee, entry.Status);
        Assert.True(entry.IsAutoGenerated);
        Assert.Equal(AccountingService.SourceInvoice, entry.SourceEntityType);
        Assert.Null(entry.ValidatedBy);
        Assert.Null(entry.ValidatedAt);
    }

    [Fact]
    public async Task BrouillardEnabled_CancellingValidatedSale_AddsValidatedReversal()
    {
        var invoice = NewSaleInvoice();
        AddLine(invoice, "Prestation", 100m);
        SetStamp(invoice, 1m);

        var (service, captured, journals) = BuildService();
        var generated = await service.GenerateInvoiceSaleEntryAsync(invoice, CancellationToken.None);
        Assert.True(generated.IsSuccess, generated.Error?.Description);

        var original = Assert.Single(captured);
        var cancelled = await service.ReverseInvoiceSaleEntryAsync(invoice.Id, "FAC-2026-0001", CancellationToken.None);

        Assert.True(cancelled.IsSuccess, cancelled.Error?.Description);
        Assert.Equal(2, captured.Count);
        var reversal = captured.Single(e => e.SourceEntityType == AccountingService.SourceInvoiceCancelled);
        Assert.Equal(JournalEntryStatus.Validee, reversal.Status);
        Assert.True(reversal.IsAutoGenerated);
        Assert.Equal(original.Id, reversal.ReversesEntryId);
        Assert.Null(reversal.ValidatedBy);
        Assert.Null(reversal.ValidatedAt);
        Assert.True(original.IsReversed);
        Assert.Equal(original.Lines.Sum(l => l.DebitAmount.Amount), reversal.Lines.Sum(l => l.CreditAmount.Amount));

        journals.Verify(x => x.RemoveAsync(It.IsAny<JournalEntry>(), It.IsAny<CancellationToken>()), Times.Never);
        journals.Verify(x => x.AddAsync(It.IsAny<JournalEntry>(), It.IsAny<CancellationToken>()), Times.Exactly(2));
    }

    private static (AccountingService service, List<JournalEntry> captured, Mock<IJournalEntryRepository> journals) BuildService()
    {
        var chart = new Mock<IChartOfAccountRepository>();
        chart.Setup(x => x.CountAsync(It.IsAny<CancellationToken>())).ReturnsAsync(50);
        chart.Setup(x => x.GetByAccountNumberAsync(It.IsAny<string>(), It.IsAny<CancellationToken>()))
            .ReturnsAsync((string n, CancellationToken _) => n switch
            {
                "4371" => Acc("4371", AccountNatureType.Credit),
                "436711" => Acc("436711", AccountNatureType.Credit),
                "707" => Acc("707", AccountNatureType.Credit),
                "4111" => Acc("4111", AccountNatureType.Debit),
                _ => Acc(n)
            });

        var periodService = new Mock<IAccountingPeriodService>();
        var period = AccountingPeriod.Create(2026, 7, new DateTime(2026, 7, 1), new DateTime(2026, 7, 31));
        periodService.Setup(x => x.EnsureOpenPeriodAsync(It.IsAny<DateTime>(), It.IsAny<CancellationToken>()))
            .ReturnsAsync(Result.Success(period));

        var captured = new List<JournalEntry>();
        var journals = new Mock<IJournalEntryRepository>();
        journals.Setup(x => x.GetBySourceAsync(It.IsAny<string>(), It.IsAny<Guid>(), It.IsAny<CancellationToken>()))
            .ReturnsAsync((string type, Guid id, CancellationToken _) =>
                captured.FirstOrDefault(e => e.SourceEntityType == type && e.SourceEntityId == id));
        journals.Setup(x => x.ReserveNextEntryNumberAsync(It.IsAny<string>(), It.IsAny<int>(), It.IsAny<CancellationToken>()))
            .ReturnsAsync(13);
        journals.Setup(x => x.AddAsync(It.IsAny<JournalEntry>(), It.IsAny<CancellationToken>()))
            .Callback<JournalEntry, CancellationToken>((e, _) => captured.Add(e))
            .ReturnsAsync((JournalEntry e, CancellationToken _) => e);

        var service = new AccountingService(
            chart.Object,
            periodService.Object,
            journals.Object,
            new Mock<IWithholdingTaxRepository>().Object,
            new Mock<IDepreciationRateCategoryRepository>().Object,
            new Mock<ITenantDbContextFactory>().Object,
            NullLogger<AccountingService>.Instance,
            Options.Create(new AccountingSettings { BrouillardEnabled = true }));

        return (service, captured, journals);
    }

    private static ChartOfAccount Acc(string number, AccountNatureType nature = AccountNatureType.Debit) =>
        ChartOfAccount.Create(number, $"Compte {number}", int.Parse(number[..1]), null, nature).Value;

    private static Invoice NewSaleInvoice()
    {
        var address = Address.Create("1 rue de la République", "Tunis", "Tunis").Value;
        var email = Email.Create("client@example.com").Value;
        var client = Client.Create("Client test", ClientType.Individual, address, email).Value;
        var result = Invoice.Create(InvoiceNumber.Create("FAC", 2026, 1), client, new DateTime(2026, 7, 13));
        Assert.True(result.IsSuccess, result.Error?.Description);
        return result.Value;
    }

    private static void AddLine(Invoice invoice, string designation, decimal unitHt)
    {
        var add = invoice.AddCustomLine(
            designation, null, 1m, "Unité", Money.Create(unitHt, Money.DefaultCurrency),
            VatRate.Standard, isFodecApplicable: false, fodecRatePercent: 1m);
        Assert.True(add.IsSuccess, add.Error?.Description);
    }

    private static void SetStamp(Invoice invoice, decimal signedAmount)
    {
        var set = invoice.SetFiscalStampAmount(Money.FromSignedAmount(signedAmount, Money.DefaultCurrency));
        Assert.True(set.IsSuccess, set.Error?.Description);
    }
}
