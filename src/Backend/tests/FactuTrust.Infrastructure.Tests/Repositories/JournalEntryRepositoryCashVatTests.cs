    [Fact]
    public async Task ManualReversalDraft_EditedByFirm_SignedAmountsFollowEditedLines()
    {
        var period = SeedPeriod();
        var op = SeedCashSalesOperation(VatRate.Standard);
        var original = CashSaleEntry(1, new DateTime(2026, 3, 5), ht: 100m, vat: 19m, sourceOperationId: op.Id,
            accountingPeriodId: period.Id);
        var reversal = ReversalOf(original, 2, new DateTime(2026, 3, 20), status: JournalEntryStatus.Brouillon,
            accountingPeriodId: period.Id);
        original.MarkReversedBy(reversal.Id);
        await SeedAsync([op], [original, reversal]);

        var handler = BuildUpdateHandler();
        var editResult = await handler.Handle(
            new UpdateDraftJournalEntryCommand(reversal.Id, new UpdateDraftJournalEntryRequest
            {
                Label = "Extourne corrigée par le cabinet",
                Lines = new[]
                {
                    new ManualJournalLineRequest { AccountNumber = "5411", LineLabel = "Caisse", Debit = 0m, Credit = 150m + 28.5m },
                    new ManualJournalLineRequest { AccountNumber = "707", LineLabel = "Ventes HT", Debit = 150m, Credit = 0m },
                    new ManualJournalLineRequest { AccountNumber = "436711", LineLabel = "TVA collectée", Debit = 28.5m, Credit = 0m }
                }
            }),
            CancellationToken.None);
        Assert.True(editResult.IsSuccess, editResult.Error?.Description);

        var result = await _repository.GetPostedCashSaleVatByRateAsync(new DateTime(2026, 3, 1), new DateTime(2026, 3, 31));

        // L'origine (mars) reste à +100/+19 ; l'extourne éditée porte désormais -150/-28.5 (taux
        // résolu depuis l'opération de caisse d'ORIGINE, pas depuis les lignes éditées — D2).
        result.Should().ContainSingle();
        result[0].RatePercent.Should().Be(19);
        result[0].HtBase.Should().Be(100m - 150m);
        result[0].VatAmount.Should().Be(19m - 28.5m);
    }

