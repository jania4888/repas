    /// <summary>Extourne manuelle : lignes inversées (miroir exact) par rapport à l'écriture d'origine.</summary>
    private static JournalEntry ReversalOf(
        JournalEntry original, int entryNumber, DateTime date, JournalEntryStatus status = JournalEntryStatus.Validee,
        Guid? accountingPeriodId = null)
    {
        var mirrored = original.Lines
            .OrderBy(l => l.LineNumber)
            .Select(l => new JournalLineInput(
                l.AccountNumber, l.Label, l.CreditAmount.Amount, l.DebitAmount.Amount, l.ThirdPartyId, l.ThirdPartyKind))
            .ToList();

        return JournalEntry.Create(
            entryNumber, original.JournalCode, date, $"Extourne {original.JournalCode}-{original.EntryNumber}",
            accountingPeriodId ?? Guid.NewGuid(), isAutoGenerated: false, sourceEntityType: "ManualReversal", sourceEntityId: original.Id,
            lineInputs: mirrored, reversesEntryId: original.Id, initialStatus: status).Value;
    }

    private async Task SeedAsync(IEnumerable<CashOperation> operations, IEnumerable<JournalEntry> entries)
    {
        await using var context = _contextFactory.CreateContext();
        context.CashOperations.AddRange(operations);
        context.JournalEntries.AddRange(entries);
        await context.SaveChangesAsync();
    }

