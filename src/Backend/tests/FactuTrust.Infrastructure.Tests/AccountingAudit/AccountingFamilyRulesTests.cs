    private static int _invoiceSequence = 1;

    /// <summary>
    /// Facture validée d'une ligne à 100 HT en TVA 19 %. Les totaux sont calculés par le domaine :
    /// les tests lisent <c>TotalVat</c> plutôt que de coder en dur une valeur qui dériverait au
    /// moindre changement de règle de calcul (timbre, FODEC).
    /// </summary>
    private static Invoice NewValidatedInvoice()
    {
        var invoice = Invoice.Create(
            InvoiceNumber.Create("FAC", Year, _invoiceSequence++),
            NewClient(),
            new DateTime(Year, 4, 10)).Value;

        Assert.True(invoice
            .AddCustomLine("Article", null, 1m, "Unité", Money.Create(100m), VatRate.Standard)
            .IsSuccess);
        Assert.True(invoice.Validate().IsSuccess);
        invoice.SetAuditInfo("test", false);
        return invoice;
    }

    private static Client NewClient() =>
        Client.Create(
            "Client test", ClientType.Business,
            Address.Create("Rue 1", "Tunis", "Tunis").Value,
            Email.Create("client@test.tn").Value,
            NIF.Create("1234567/A/B/C/000").Value).Value;

    /// <summary>
    /// Écriture de vente rattachée à la facture, avec un montant de TVA imposé — c'est le levier
    /// des tests : faire diverger le comptabilisé du document.
    /// </summary>
    private static JournalEntry BookInvoice(int number, Invoice invoice, decimal bookedVat)
    {
        var ht = invoice.SubTotal.Amount;
        return Entry(number, invoice.IssueDate, AccountingService.SourceInvoice, invoice.Id,
            new JournalLineInput("4111", "Client", ht + bookedVat, 0m, null, ThirdPartyKind.None),
            new JournalLineInput("707", "Vente", 0m, ht, null, ThirdPartyKind.None),
            new JournalLineInput("436711", "TVA collectée", 0m, bookedVat, null, ThirdPartyKind.None));
    }

    private static async Task SeedLetteringAsync(
        TestTenantDbContextFactory factory, bool sameAccount, bool balanced, bool dropOneMember)
    {
        await using var db = factory.CreateContext();

        var secondAccount = sameAccount ? "4111" : "4011";
        var creditAmount = balanced ? 100m : 60m;

        var entry = Entry(1, new DateTime(Year, 7, 1), null, null,
            new JournalLineInput("4111", "Facture", 100m, 0m, null, ThirdPartyKind.None),
            new JournalLineInput(secondAccount, "Règlement", 0m, creditAmount, null, ThirdPartyKind.None),
            new JournalLineInput("532", "Banque", creditAmount, 0m, null, ThirdPartyKind.None),
            new JournalLineInput("707", "Vente", 0m, 100m, null, ThirdPartyKind.None));
        db.JournalEntries.Add(entry);
        await db.SaveChangesAsync();

        var lines = entry.Lines.Take(2).Select(l => l.Id).ToList();
        // Un membre pointant un identifiant inexistant simule la ligne disparue.
        var memberIds = dropOneMember ? new List<Guid> { lines[0], Guid.NewGuid() } : lines;

        var group = LetteringGroup.Create(
            "AA0001", "4111", Money.Create(100m), memberIds, isPartial: false).Value;
        group.SetAuditInfo("test", false);
        db.LetteringGroups.Add(group);
        await db.SaveChangesAsync();
    }
