/// <summary>
/// Famille « Comptable » du réviseur. Chaque règle est éprouvée sur le cas sain (silence attendu)
/// ET sur le cas dégradé : une règle qui ne se tait pas sur un dossier propre est aussitôt
/// désactivée par l'utilisateur, et une règle muette ne sert à rien.
