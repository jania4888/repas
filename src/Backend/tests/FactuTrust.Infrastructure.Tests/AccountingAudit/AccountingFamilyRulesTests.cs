    private sealed class TestTenantDbContextFactory : ITenantDbContextFactory
    {
        private readonly string _databaseName;
        public TestTenantDbContextFactory(string databaseName) => _databaseName = databaseName;

        public TenantDbContext CreateContext()
        {
            var options = new DbContextOptionsBuilder<TenantDbContext>()
                .UseInMemoryDatabase(_databaseName)
                .Options;
            return new TenantDbContext(options);
        }
    }

    private const int Year = 2026;

    private static TestTenantDbContextFactory NewFactory(string label) => new($"{label}_{Guid.NewGuid()}");

    private static AuditEvaluationContextImpl Context(TenantDbContext db) => new(
        db,
        new AccountingSettings(),
        Year,
        new DateOnly(Year, 1, 1),
        new DateOnly(Year, 12, 31),
        Array.Empty<AccountingControlRuleSetting>(),
        moduleCodesFilter: null);

    private static async Task<IReadOnlyList<AnomalyCandidate>> EvaluateAsync(
        TestTenantDbContextFactory factory, IAccountingAuditRule rule)
    {
        await using var db = factory.CreateContext();
        return await rule.EvaluateAsync(Context(db), CancellationToken.None);
    }

    private static JournalEntry Entry(
        int number,
        DateTime date,
        string? sourceType,
        Guid? sourceId,
        params JournalLineInput[] lines)
    {
        var entry = JournalEntry.Create(
            number, "JV", date, $"Écriture {number}", Guid.NewGuid(),
            isAutoGenerated: sourceType is not null,
            sourceEntityType: sourceType,
            sourceEntityId: sourceId,
            lines,
            initialStatus: JournalEntryStatus.Validee).Value;
        entry.SetAuditInfo("test", false);
        return entry;
    }

    // ── TVA comptabilisée vs document ─────────────────────────────────────────────────────

    /// <summary>Facture dont la TVA comptabilisée correspond : la règle doit rester muette.</summary>
    [Fact]
    public async Task Vat_versus_document_is_silent_when_amounts_match()
    {
        var factory = NewFactory("VatMatch");
        var invoice = NewValidatedInvoice();

        await using (var db = factory.CreateContext())
        {
            db.Invoices.Add(invoice);
            db.JournalEntries.Add(BookInvoice(1, invoice, bookedVat: invoice.TotalVat.Amount));
            await db.SaveChangesAsync();
        }

        Assert.Empty(await EvaluateAsync(factory, new VatVersusDocumentAuditRule()));
    }

    [Fact]
    public async Task Vat_versus_document_flags_a_divergence_and_reports_the_gap()
    {
        var factory = NewFactory("VatGap");
        var invoice = NewValidatedInvoice();
        var documentVat = invoice.TotalVat.Amount;
        var bookedVat = documentVat - 6m;

        await using (var db = factory.CreateContext())
        {
            db.Invoices.Add(invoice);
            db.JournalEntries.Add(BookInvoice(1, invoice, bookedVat));
            await db.SaveChangesAsync();
        }

        var anomaly = Assert.Single(await EvaluateAsync(factory, new VatVersusDocumentAuditRule()));
        Assert.Equal(6m, anomaly.Amount);
    }

    /// <summary>
    /// Un écart d'un millime relève de l'arrondi, pas de l'anomalie : le signaler noierait le
    /// réviseur sous des faux positifs sur chaque facture à taux mêlés.
    /// </summary>
    [Fact]
    public async Task Vat_versus_document_tolerates_a_millime_rounding_gap()
    {
        var factory = NewFactory("VatRounding");
        var invoice = NewValidatedInvoice();

        await using (var db = factory.CreateContext())
        {
            db.Invoices.Add(invoice);
            db.JournalEntries.Add(BookInvoice(1, invoice, invoice.TotalVat.Amount + 0.001m));
            await db.SaveChangesAsync();
        }

        Assert.Empty(await EvaluateAsync(factory, new VatVersusDocumentAuditRule()));
    }

    /// <summary>Deux écritures en écart doivent produire deux anomalies distinctes, pas une qui écrase l'autre.</summary>
    [Fact]
    public async Task Vat_versus_document_produces_distinct_fingerprints_per_entry()
    {
        var factory = NewFactory("VatFingerprints");
        var first = NewValidatedInvoice();
        var second = NewValidatedInvoice();

        await using (var db = factory.CreateContext())
        {
            db.Invoices.AddRange(first, second);
            db.JournalEntries.Add(BookInvoice(1, first, first.TotalVat.Amount - 6m));
            db.JournalEntries.Add(BookInvoice(2, second, second.TotalVat.Amount - 6m));
            await db.SaveChangesAsync();
        }

        var found = await EvaluateAsync(factory, new VatVersusDocumentAuditRule());

        Assert.Equal(2, found.Count);
        Assert.Equal(2, found.Select(f => f.Fingerprint).Distinct().Count());
    }

    // ── Tiers vs compte collectif ─────────────────────────────────────────────────────────

    [Fact]
    public async Task Third_party_mismatch_is_silent_on_well_formed_entries()
    {
        var factory = NewFactory("ThirdPartyOk");
        var clientId = Guid.NewGuid();

        await using (var db = factory.CreateContext())
        {
            db.JournalEntries.Add(Entry(1, new DateTime(Year, 5, 2), null, null,
                new JournalLineInput("4111", "Client", 100m, 0m, clientId, ThirdPartyKind.Client),
                new JournalLineInput("707", "Vente", 0m, 100m, null, ThirdPartyKind.None)));
            await db.SaveChangesAsync();
        }

        Assert.Empty(await EvaluateAsync(factory, new ThirdPartyAccountMismatchAuditRule()));
    }

    [Fact]
    public async Task Third_party_mismatch_separates_the_three_kinds_of_breakage()
    {
        var factory = NewFactory("ThirdPartyKinds");

        await using (var db = factory.CreateContext())
        {
            // Client sur un 607 : mauvaise classe.
            db.JournalEntries.Add(Entry(1, new DateTime(Year, 5, 2), null, null,
                new JournalLineInput("607", "Achat", 100m, 0m, Guid.NewGuid(), ThirdPartyKind.Client),
                new JournalLineInput("532", "Banque", 0m, 100m, null, ThirdPartyKind.None)));
            // Fournisseur sur un 411 : sens inversé.
            db.JournalEntries.Add(Entry(2, new DateTime(Year, 5, 3), null, null,
                new JournalLineInput("4111", "Client", 0m, 50m, Guid.NewGuid(), ThirdPartyKind.Supplier),
                new JournalLineInput("532", "Banque", 50m, 0m, null, ThirdPartyKind.None)));
            // Compte collectif sans tiers : balance auxiliaire incomplète.
            db.JournalEntries.Add(Entry(3, new DateTime(Year, 5, 4), null, null,
                new JournalLineInput("4011", "Fournisseur", 0m, 70m, null, ThirdPartyKind.None),
                new JournalLineInput("607", "Achat", 70m, 0m, null, ThirdPartyKind.None)));
            await db.SaveChangesAsync();
        }

        var found = await EvaluateAsync(factory, new ThirdPartyAccountMismatchAuditRule());

        Assert.Equal(3, found.Count);
        Assert.Equal(3, found.Select(f => f.Fingerprint).Distinct().Count());
    }

    /// <summary>
    /// Plan « Matricule fiscal sur les comptes auxiliaires » §5.8 : un compte auxiliaire
    /// individualise déjà le tiers par lui-même, une ligne posée sans fiche dessus n'est pas une
    /// rupture. Le compte collectif « nu » (sans compte auxiliaire ni fiche), lui, reste signalé —
    /// la régression à surveiller est que l'exclusion ne s'étende pas au collectif.
    /// </summary>
    [Fact]
    public async Task Third_party_mismatch_excludes_an_auxiliary_account_without_a_fiche_but_still_flags_the_bare_collective()
    {
        var factory = NewFactory("ThirdPartyAuxiliaryExclusion");

        await using (var db = factory.CreateContext())
        {
            db.ChartOfAccounts.Add(ChartOfAccount.Create(
                "40114", "Fournisseur X", 4, null, AccountNatureType.Credit,
                accountType: AccountType.Supplier, isAuxiliary: true).Value);
            // Ligne sur le compte auxiliaire, sans fiche attachée : ne doit pas être signalée.
            db.JournalEntries.Add(Entry(1, new DateTime(Year, 5, 2), null, null,
                new JournalLineInput("40114", "Fournisseur X", 0m, 70m, null, ThirdPartyKind.None),
                new JournalLineInput("607", "Achat", 70m, 0m, null, ThirdPartyKind.None)));
            // Ligne sur le collectif nu, sans fiche attachée : doit rester signalée.
            db.JournalEntries.Add(Entry(2, new DateTime(Year, 5, 3), null, null,
                new JournalLineInput("4011", "Fournisseur", 0m, 50m, null, ThirdPartyKind.None),
                new JournalLineInput("607", "Achat", 50m, 0m, null, ThirdPartyKind.None)));
            await db.SaveChangesAsync();
        }

        var found = await EvaluateAsync(factory, new ThirdPartyAccountMismatchAuditRule());

        var anomaly = Assert.Single(found);
        Assert.DoesNotContain("40114", anomaly.Lines.Select(l => l.AccountNumber));
        Assert.Contains("4011", anomaly.Lines.Select(l => l.AccountNumber));
    }

