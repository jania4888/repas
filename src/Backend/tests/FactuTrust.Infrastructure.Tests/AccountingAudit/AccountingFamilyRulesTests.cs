    // ── Extourne manquante ────────────────────────────────────────────────────────────────

    [Fact]
    public async Task Reversal_missing_flags_an_entry_marked_reversed_without_counterpart()
    {
        var factory = NewFactory("ReversalFlagged");

        await using (var db = factory.CreateContext())
        {
            var entry = Entry(1, new DateTime(Year, 6, 1), null, null,
                new JournalLineInput("607", "Achat", 100m, 0m, null, ThirdPartyKind.None),
                new JournalLineInput("532", "Banque", 0m, 100m, null, ThirdPartyKind.None));
            // Marque d'extourne pointant une écriture qui n'existe pas.
            entry.MarkReversedBy(Guid.NewGuid());
            db.JournalEntries.Add(entry);
            await db.SaveChangesAsync();
        }

        var anomaly = Assert.Single(await EvaluateAsync(factory, new ReversalMissingAuditRule()));
        Assert.Contains("contre-passation", anomaly.Description);
        Assert.Equal((int)PreClosingSeverity.Blocking, anomaly.Severity);
    }

    [Fact]
    public async Task Reversal_missing_flags_a_cancelled_invoice_never_reversed()
    {
        var factory = NewFactory("ReversalCancelled");
        var invoice = NewValidatedInvoice();
        Assert.True(invoice.Cancel("annulation de test").IsSuccess);

        await using (var db = factory.CreateContext())
        {
            db.Invoices.Add(invoice);
            db.JournalEntries.Add(BookInvoice(1, invoice, invoice.TotalVat.Amount));
            await db.SaveChangesAsync();
        }

        var anomaly = Assert.Single(await EvaluateAsync(factory, new ReversalMissingAuditRule()));
        Assert.Contains("annulée", anomaly.Description);
        Assert.Equal(invoice.TotalAmount.Amount, anomaly.Amount);
    }

    [Fact]
    public async Task Reversal_missing_is_silent_when_the_counter_entry_exists()
    {
        var factory = NewFactory("ReversalOk");
        var invoice = NewValidatedInvoice();
        Assert.True(invoice.Cancel("annulation de test").IsSuccess);

        await using (var db = factory.CreateContext())
        {
            db.Invoices.Add(invoice);

            var source = BookInvoice(1, invoice, invoice.TotalVat.Amount);
            db.JournalEntries.Add(source);

            var ht = invoice.SubTotal.Amount;
            var vat = invoice.TotalVat.Amount;
            var counter = JournalEntry.Create(
                2, "JV", new DateTime(Year, 6, 2), "Extourne", Guid.NewGuid(),
                isAutoGenerated: true,
                sourceEntityType: AccountingService.SourceInvoiceCancelled,
                sourceEntityId: invoice.Id,
                [
                    new JournalLineInput("707", "Vente", ht, 0m, null, ThirdPartyKind.None),
                    new JournalLineInput("436711", "TVA collectée", vat, 0m, null, ThirdPartyKind.None),
                    new JournalLineInput("4111", "Client", 0m, ht + vat, null, ThirdPartyKind.None)
                ],
                reversesEntryId: source.Id,
                initialStatus: JournalEntryStatus.Validee).Value;
            counter.SetAuditInfo("test", false);
            db.JournalEntries.Add(counter);

            await db.SaveChangesAsync();
        }

        Assert.Empty(await EvaluateAsync(factory, new ReversalMissingAuditRule()));
    }

